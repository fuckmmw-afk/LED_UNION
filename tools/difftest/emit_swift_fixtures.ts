/**
 * Pin the native Swift drivers to the TypeScript ones.
 *
 * The TypeScript builders are the implementation that is diffed against the original
 * apps (see emit_ts_frames.ts). This script replays one command sequence per
 * advertised name through them and writes the frames as a Swift test fixture, so
 * `swift test` fails as soon as a native frame drifts by a single byte.
 *
 * Run: node tools/difftest/emit_swift_fixtures.ts > Tests/LEDUnionCore/TSFrameFixtures.swift
 */
import { drivers } from '../../src/lib/protocol/index.ts'

const NAMES = [
  'LEDBLE-00-9B67',
  'LEDBLE-03-1',
  'LEDSTAGE-1',
  'LEDDMX-00-1',
  'LEDDMX-02-1',
  'LEDCAR-00-1',
  'LEDCAR-01-1',
  'LEDCAR-02-1',
  'LEDSMART-1',
  'LEDSUN-1',
  'LEDLIKE-1',
  'LEDPHO-1',
  'MELK-OF21 9D',
  'MELK-OC-1',
  'MELK-OBCT-1',
  'ELK-BLEDOM',
  'XSL-Light',
  'BLEDIM',
]

type Step = { command: string; frame: Uint8Array | undefined }

const out: string[] = []
const effectTables: string[] = []

for (const name of NAMES) {
  const d = drivers.find((x) => x.matches(name))
  if (!d) throw new Error(`no driver claims ${name}`)
  const run: Step[] = []
  const add = (command: string, frame: Uint8Array | undefined) => run.push({ command, frame })
  add('power:1', d.power(true, name))
  add('power:0', d.power(false, name))
  for (const [r, g, b] of [[0x11, 0x22, 0x33], [255, 0, 128], [0, 0, 0], [255, 255, 255]]) {
    add(`rgb:${r},${g},${b}`, d.rgb(r, g, b, name))
  }
  for (const v of [0, 37, 50, 100]) add(`brightness:${v}`, d.brightness(v, name))
  for (const v of [0, 50, 73, 100]) add(`speed:${v}`, d.speed(v, name))
  const table = d.effects(name)
  const picks = [table[0], table[Math.floor(table.length / 2)], table[table.length - 1]]
  const scene = table.find((e) => e.group === 'Scenes')
  if (scene) picks.push(scene)
  for (const e of picks) {
    if (e) add(`effect:${e.id}:${e.group ?? ''}`, d.effect(e, name))
  }
  for (const v of [0, 37, 100]) add(`white:${v}`, d.white?.(v, name))
  add('cct:30,70', d.cct?.(30, 70, name))
  for (const step of run) {
    const bytes = step.frame ? `[${[...step.frame].join(', ')}]` : 'nil'
    out.push(`    TSFrameFixture(name: ${JSON.stringify(name)}, command: ${JSON.stringify(step.command)}, frame: ${bytes}),`)
  }
  effectTables.push(`    ${JSON.stringify(name)}: [${table.map((e) => e.id).join(', ')}],`)
}

console.log(`// GENERATED by tools/difftest/emit_swift_fixtures.ts — do not edit by hand.
// Frames produced by the TypeScript drivers for the same command sequence.

struct TSFrameFixture: Sendable {
    let name: String
    let command: String
    let frame: [UInt8]?
}

let tsFrameFixtures: [TSFrameFixture] = [
${out.join('\n')}
]

let tsEffectIDs: [String: [Int]] = [
${effectTables.join('\n')}
]`)
